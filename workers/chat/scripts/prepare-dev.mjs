import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseEnv } from "node:util";

const localSecretNames = ["ENFORCEMENT_SECRET", "IP_GUARD_SECRET"];
const localAllowedOrigins = "http://localhost:3002,http://127.0.0.1:3002";
const defaultDevVarsPath = fileURLToPath(new URL("../.dev.vars", import.meta.url));

/** 로컬 실행에만 쓰며 기존 키를 바꾸지 않는다. 값은 콘솔에 출력하지 않는다. */
export const ensureChatDevVars = (devVarsPath = defaultDevVarsPath) => {
  const hasDevVarsFile = existsSync(devVarsPath);
  const originalContent = hasDevVarsFile ? readFileSync(devVarsPath, "utf8") : "";
  const configuredValues = parseEnv(originalContent);
  const additions = [];
  const addedNames = [];

  for (const secretName of localSecretNames) {
    if (!configuredValues[secretName]?.trim()) {
      additions.push(`${secretName}=${randomBytes(32).toString("hex")}`);
      addedNames.push(secretName);
    }
  }

  if (!configuredValues.CHAT_ALLOWED_ORIGINS?.trim()) {
    additions.push(`CHAT_ALLOWED_ORIGINS=${localAllowedOrigins}`);
    addedNames.push("CHAT_ALLOWED_ORIGINS");
  }

  if (!configuredValues.SPACE_DISABLE_IP_CONNECTION_LIMIT?.trim()) {
    additions.push("SPACE_DISABLE_IP_CONNECTION_LIMIT=true");
    addedNames.push("SPACE_DISABLE_IP_CONNECTION_LIMIT");
  }

  if (additions.length > 0) {
    const prefix = hasDevVarsFile
      ? originalContent
      : "# Local development only. Generated by pnpm chat:dev.\n";
    const separator = prefix.endsWith("\n") ? "" : "\n";
    writeFileSync(devVarsPath, `${prefix}${separator}${additions.join("\n")}\n`, {
      encoding: "utf8",
      mode: 0o600,
    });
  }

  return addedNames;
};

if (
  process.argv[1] &&
  existsSync(process.argv[1]) &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
) {
  const addedNames = ensureChatDevVars();
  if (addedNames.length > 0) {
    console.info(`[chat:dev] 로컬 설정 준비: ${addedNames.join(", ")}`);
  }
}
